def classify(text):
    payload = json.dumps({"text": text}).encode("utf-8")

    request = urllib.request.Request(
        API_URL,
        data=payload,
        headers={"Content-Type": "application/json"},
        method="POST",
    )

    with urllib.request.urlopen(request, timeout=30) as response:
        return json.loads(response.read().decode("utf-8"))



def main():
    total = 0
    correct = 0
    methods = {"rules": 0, "semantic": 0}
    results = []

    print("\n=== CLASSIFIER FULL PIPELINE TEST ===\n")

    for expected, phrases in TEST_CASES.items():
        print(f"\n--- {expected.upper()} ---")

        for phrase in phrases:
            total += 1

            try:
                result = classify(phrase)

                actual = result["skill"]
                score = result["score"]
                method = result.get("method", "unknown")
                margin = result.get("margin", 0)

                if method in methods:
                    methods[method] += 1

                passed = actual == expected

                if passed:
                    correct += 1

                status = "PASS" if passed else "FAIL"

                alternatives = result.get("alternatives", [])
                second = (
                    f'{alternatives[1]["skill"]}: '
                    f'{alternatives[1]["score"]:.3f}'
                    if len(alternatives) > 1
                    else "-"
                )

                print(
                    f"[{status}] {phrase}\n"
                    f"       expected={expected}, actual={actual}\n"
                    f"       method={method}, score={score:.3f}, "
                    f"margin={margin:.3f}\n"
                    f"       second={second}"
                )

                results.append({
                    "text": phrase,
                    "expected": expected,
                    "actual": actual,
                    "method": method,
                    "score": score,
                    "margin": margin,
                    "passed": passed,
                })

            except Exception as error:
                print(f"[ERROR] {phrase}: {error}")

    print("\n=== SUMMARY ===")
    print(f"Correct: {correct}/{total}")
    print(f"Accuracy: {correct / total * 100:.1f}%" if total else "No tests")

    print("\nMethods:")
    for method, count in methods.items():
        print(f"  {method}: {count}")

    failed = [item for item in results if not item["passed"]]

    if failed:
        print("\nMisclassified phrases:")
        for item in failed:
            print(
                f'  "{item["text"]}" '
                f'expected={item["expected"]}, '
                f'actual={item["actual"]}, '
                f'method={item["method"]}'
            )


if __name__ == "__main__":
    main()
